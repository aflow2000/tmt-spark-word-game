/* ============================================================
   Generates supabase/schedule/fortnightly.sql — the production issue
   calendar for the Supabase editions: one Spark Word every 14 days,
   taken in order from assets/spark-word-daily-words.js.

     node scripts/build-schedule-sql.js                       # defaults below
     START=2026-09-22 FIRST_ISSUE=1 EVERY=14 node scripts/build-schedule-sql.js

   Issues are inserted as `scheduled`; sw_activate_due() (called by every
   player read) flips each one to `active` on its publication date and
   archives the previous one — no cron job needed. Editors can still
   change any issue's word, hint or date in the dashboard.
   ============================================================ */
const fs = require("fs");
const path = require("path");
const R = path.join(__dirname, "..");

const START = process.env.START || "2026-09-08";     // publication date of the first issue (YYYY-MM-DD)
const FIRST = parseInt(process.env.FIRST_ISSUE || "15", 10); // the site's newsletter is on Edition 014 → Spark Word starts with 015
const EVERY = parseInt(process.env.EVERY || "14", 10);      // days between issues

const src = fs.readFileSync(path.join(R, "assets/spark-word-daily-words.js"), "utf8");
const sandbox = { window: {} }; new Function("window", src)(sandbox.window);
const words = sandbox.window.SPARK_WORD_SCHEDULE.words;

const q = (s) => "$q$" + String(s).replace(/\$q\$/g, "") + "$q$";   // dollar-quoted: newlines and apostrophes are safe
const s0 = START.split("-").map(Number);
const dateOf = (k) => new Date(Date.UTC(s0[0], s0[1] - 1, s0[2]) + k * EVERY * 86400000).toISOString().slice(0, 10);
const seen = new Set();
words.forEach((w) => { if (!/^[A-Z]{5}$/.test(w.w) || seen.has(w.w)) throw new Error("bad or duplicate word " + w.w); seen.add(w.w); });

const last = FIRST + words.length - 1;
let sql = `-- ============================================================
-- SPARK WORD — fortnightly schedule · issues ${String(FIRST).padStart(3, "0")}–${String(last).padStart(3, "0")}
-- Generated by scripts/build-schedule-sql.js from assets/spark-word-daily-words.js
-- One word every ${EVERY} days from ${START} (Issue ${String(FIRST).padStart(3, "0")}) to ${dateOf(words.length - 1)} (Issue ${String(last).padStart(3, "0")}).
-- Issues go live by themselves on their date (sw_activate_due). Safe to re-run: existing issue numbers are left untouched.
-- ============================================================

-- The answers join the word bank (so the dashboard's reuse guard and search know them);
-- words already in the bank keep their definition and get the newer, easier hint.
insert into word_bank (word, category, definition, hint, active) values
${words.map((w) => `  (${q(w.w)}, ${q(w.c)}, ${q(w.e)}, ${q(w.h)}, true)`).join(",\n")}
on conflict (word) do update set hint = excluded.hint;

insert into issues (issue_number, title, publication_date, answer, category, hint, explanation, status) values
${words.map((w, k) => `  (${FIRST + k}, null, '${dateOf(k)}', ${q(w.w)}, ${q(w.c)}, ${q(w.h)}, ${q(w.e)}, 'scheduled')`).join(",\n")}
on conflict (issue_number) do nothing;

-- The easier hint rhythm the daily edition uses: hint after 2 guesses, first letter after 4.
update sw_settings set value = '2' where key = 'hint_unlock_after';
update sw_settings set value = '4' where key = 'second_spark_after';

-- Bring the calendar up to date right away (the first read would do this anyway).
select sw_activate_due() as issues_activated;
`;
fs.mkdirSync(path.join(R, "supabase/schedule"), { recursive: true });
fs.writeFileSync(path.join(R, "supabase/schedule/fortnightly.sql"), sql);
console.log(`supabase/schedule/fortnightly.sql · issues ${FIRST}–${last} · ${START} → ${dateOf(words.length - 1)} every ${EVERY} days · ${(sql.length / 1024).toFixed(0)} KB`);
